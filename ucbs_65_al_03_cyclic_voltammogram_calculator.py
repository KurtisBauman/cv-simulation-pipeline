def main():
    print("=" * 62)
    print("  CV Simulator + MECSim Master.inp Generator (combined)")
    print("  Enter your reactions ONCE -- get plots AND Master.inp")
    print("=" * 62)

    print("\n[Step 1] First half-cell reaction (required):")
    cv = input_cv_params()

    reactions: List[HalfCellReaction] = []
    reactions.append(input_reaction(1, cv.T))

    idx = 2
    while True:
        if get_bool(f"\n  Add another reaction (#{idx})?", False):
            reactions.append(input_reaction(idx, cv.T))
            idx += 1
        else:
            break

    #Run the simulation
    print(f"\n  Running simulation for {len(reactions)} reaction(s)...")
    E, individual_I, I_total, labels = simulate_multi_cv(reactions, cv)
    print("  Done.")

    print("\n-- Peak Summary --")
    i_pa = np.max(I_total)
    i_pc = np.min(I_total)
    E_pa = E[np.argmax(I_total)]
    E_pc = E[np.argmin(I_total)]
    print(f"  Epa = {E_pa:.4f} V   ipa = {i_pa*1e6:.4f} uA")
    print(f"  Epc = {E_pc:.4f} V   ipc = {i_pc*1e6:.4f} uA")
    if abs(i_pc) > 0:
        print(f"  |ipa/ipc| = {abs(i_pa/i_pc):.3f}  (1.0 -> reversible)")
    if abs(E_pa - E_pc) > 0:
        print(f"  dEp = {abs(E_pa-E_pc)*1000:.1f} mV  (59/n mV -> reversible)")

    plot_results(E, individual_I, I_total, labels, reactions, cv)

    fname = "cv_data.csv"
    header = "E_V," + ",".join([f"I_{l}_A" for l in labels]) + ",I_total_A"
    data = np.column_stack([E] + individual_I + [I_total])
    np.savetxt(fname, data, delimiter=",", header=header, comments="")
    print(f"  Saved -> {fname}")

