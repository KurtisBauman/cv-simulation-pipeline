# MECSim Master.inp generator
def adjust_E0_for_temperature(E0_ref, n, dS_rxn, T):
    if dS_rxn == 0.0:
        return E0_ref
    return E0_ref + (dS_rxn / (n * F)) * (T - T0)


def adjust_ks_for_temperature(ks_ref, Ea, T):
    if Ea == 0.0:
        return ks_ref
    return ks_ref * math.exp((-Ea / R) * (1.0 / T - 1.0 / T0))


def build_master_inp(reactions: List[HalfCellReaction], cv: CVParameters, outfile="Master.inp"):

    T = cv.T
    adjusted = []
    for rxn in reactions:
        E0_T = adjust_E0_for_temperature(rxn.E0, rxn.n, rxn.dS_rxn, T)
        ks_T = adjust_ks_for_temperature(rxn.ks, rxn.Ea, T)
        adjusted.append((E0_T, ks_T))

    species = []
    sp_labels = []
    for i, rxn in enumerate(reactions):
        species.append((rxn.C0, rxn.D_O, 0))
        species.append((0.0, rxn.D_R, 0))
        sp_labels.append(f"Ox_{i+1} ({rxn.name})")
        sp_labels.append(f"Red_{i+1} ({rxn.name})")

    ec_prod_idx = {}
    for i, rxn in enumerate(reactions):
        if rxn.has_ec:
            ec_prod_idx[i] = len(species)
            species.append((0.0, rxn.D_R, 0))
            sp_labels.append(f"Prod_{i+1} ({rxn.name}, EC product)")

    n_sp = len(species)

    rxn_lines = []
    for i, rxn in enumerate(reactions):
        E0_T, ks_T = adjusted[i]
        ox_idx = 2 * i
        red_idx = 2 * i + 1

        stoic = [0] * n_sp
        stoic[ox_idx] = -1
        stoic[red_idx] = rxn.n
        stoic_str = ", ".join(str(x) for x in stoic)
        line = (f"0, {stoic_str}, 0.0e0, 0.0e0, "
                f"{E0_T:.6f}, {ks_T:.4e}, {rxn.alpha:.4f}"
                f" ! CT: {rxn.name} (n={rxn.n}, E0={E0_T:.4f}V @{T:.1f}K, ks={ks_T:.3e})")
        rxn_lines.append(line)

        if rxn.has_ec:
            prod_idx = ec_prod_idx[i]
            stoic_c = [0] * n_sp
            stoic_c[red_idx] = -1
            stoic_c[prod_idx] = 1
            stoic_c_str = ", ".join(str(x) for x in stoic_c)
            line_c = (f"1, {stoic_c_str}, {rxn.kf_chem:.4e}, {rxn.kb_chem:.4e}, "
                      f"0.0, 1.0, 0.5"
                      f" ! Chem: Red_{i+1} -> Prod_{i+1} (kf={rxn.kf_chem}, kb={rxn.kb_chem})")
            rxn_lines.append(line_c)

    lines = []

    def w(s=""):
        lines.append(s)

    w(f"{T:.2f} ! Temperature (K)")
    w(f"{cv.Ru:.4e} ! uncompensated resistance (ohms)")
    w(f"{cv.E_start:.4f} ! E_start (V)")
    w(f"{cv.E_rev:.4f} ! E_rev (V)")
    w(f"{cv.n_cycles} ! number of cycles")
    w(f"{cv.nu:.4e} ! scan speed (V/s)")
    w(f"{cv.n_pts_exp} ! 2**X points in time across n cycles (int)")
    w("0 ! correct vscan and freq for DigiPot/FFT (0=no)")
    w("1 ! output type: 0=E,i,t; 1=DigiPot compatible")
    w("0 ! EC type: 0=Butler-Volmer, 1=Marcus theory")
    w("0 ! Pre-equilibrium switch: 0=stay with user entered")
    w("0 ! fix number of timesteps (1=yes)")
    w("4000 ! number of points (not 2^N, used if above=1)")
    w("0.10 ! beta (exponential grid coefficient)")
