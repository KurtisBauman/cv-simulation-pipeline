#Data classes (shared by simulator AND MECSim generator)

@dataclass
class HalfCellReaction:
    """One electrochemical half-reaction: O + n*e- <-> R"""
    name: str = "Rxn1"
    E0: float = 0.0        # formal potential (V) AT the simulation temperature
    n: int = 1              # electrons transferred
    ks: float = 1.0        # standard rate constant (cm/s); large -> reversible
    alpha: float = 0.5      # transfer coefficient
    C0: float = 1e-6        # bulk concentration of O (mol/cm^3)
    D_O: float = 1e-5       # diffusion coeff of O (cm^2/s)
    D_R: float = 1e-5       # diffusion coeff of R (cm^2/s)
    has_ec: bool = False    # optional follow-up chemical step R -> P
    kf_chem: float = 0.0
    kb_chem: float = 0.0
    # Only used by the MECSim generator if you want extra Nernst/Arrhenius
    # correction beyond the E0/ks already entered:
    dS_rxn: float = 0.0     #reaction entropy (J/mol/K); 0 = no extra E0 shift
    Ea: float = 0.0         #activation energy (J/mol); 0 = no extra ks scaling


@dataclass
class CVParameters:
    E_start: float = 0.5
    E_rev: float = -0.5
    E_end: float = 0.5
    nu: float = 0.1
    n_cycles: int = 1
    A: float = 1.0
    Ru: float = 0.0          # uncompensated resistance, ohms, - MECSim only
    T: float = T0            # temperature (K)
    n_pts_exp: int = 12      #time resolution, 2^N points

# Finite-difference CV simulator

def simulate_cv(rxn: HalfCellReaction, cv: CVParameters) -> Tuple[np.ndarray, np.ndarray]:
    fT = F / (R * cv.T)

    n_pts_per_cycle = 600
    n_pts = n_pts_per_cycle * cv.n_cycles

    E_pts_half = n_pts_per_cycle // 2
    E_fwd = np.linspace(cv.E_start, cv.E_rev, E_pts_half, endpoint=False)
    E_back = np.linspace(cv.E_rev, cv.E_end, n_pts_per_cycle - E_pts_half, endpoint=True)
    E_one_cycle = np.concatenate([E_fwd, E_back])
    E_all = np.tile(E_one_cycle, cv.n_cycles)
    E_all = E_all[:n_pts]

    t_total = (abs(cv.E_start - cv.E_rev) + abs(cv.E_rev - cv.E_end)) * cv.n_cycles / cv.nu
    dt = t_total / n_pts

    D = rxn.D_O
    delta_max = 6 * np.sqrt(D * t_total)
    Nx = 200
    dx = delta_max / Nx

    r = D * dt / dx**2
    if r > 0.5:
        Nx = int(np.ceil(np.sqrt(D * t_total / (0.4 * dx**2)))) + 1
        dx = delta_max / Nx

    C_O = np.ones(Nx + 1) * rxn.C0
    C_R = np.zeros(Nx + 1)

    alpha1 = rxn.D_O / dx
    beta1 = rxn.D_R / dx

    currents = np.zeros(n_pts)

    for k, Ek in enumerate(E_all):
        fwd = rxn.ks * np.exp(-rxn.alpha * rxn.n * fT * (Ek - rxn.E0))
        bwd = rxn.ks * np.exp((1 - rxn.alpha) * rxn.n * fT * (Ek - rxn.E0))

        denom = alpha1 * beta1 + alpha1 * bwd + fwd * beta1
        C_O0 = (alpha1 * C_O[1] * (beta1 + bwd) + bwd * beta1 * C_R[1]) / denom
        C_R0 = (beta1 * C_R[1] + fwd * C_O0) / (beta1 + bwd)
        C_O[0] = max(0.0, C_O0)
        C_R[0] = max(0.0, C_R0)

        j = rxn.D_O * (C_O[1] - C_O[0]) / dx
        currents[k] = rxn.n * F * cv.A * j

        r_O = rxn.D_O * dt / dx**2
        r_R = rxn.D_R * dt / dx**2
        C_O_new = C_O.copy()
        C_R_new = C_R.copy()
        C_O_new[1:-1] = C_O[1:-1] + r_O * (C_O[2:] - 2 * C_O[1:-1] + C_O[:-2])
        C_R_new[1:-1] = C_R[1:-1] + r_R * (C_R[2:] - 2 * C_R[1:-1] + C_R[:-2])
        C_O_new[-1] = rxn.C0
        C_R_new[-1] = 0.0
        if rxn.has_ec and rxn.kf_chem > 0:
            k_net = rxn.kf_chem - rxn.kb_chem
            C_R_new = C_R_new * np.exp(-k_net * dt)
            C_R_new = np.maximum(C_R_new, 0)
        C_O, C_R = C_O_new, C_R_new

    return E_all, currents


def simulate_multi_cv(reactions: List[HalfCellReaction], cv: CVParameters):
    all_E, all_I, all_labels = [], [], []
    for rxn in reactions:
        E, I = simulate_cv(rxn, cv)
        all_E.append(E)
        all_I.append(I)
        all_labels.append(rxn.name)
    I_total = sum(all_I)
    return all_E[0], all_I, I_total, all_labels
#Input helpers

def get_float(prompt, default):
    while True:
        s = input(f"  {prompt} [{default}]: ").strip()
        if s == "":
            return float(default)
        try:
            return float(s)
        except ValueError:
            print("    Please enter a number.")


def get_int(prompt, default, min_val=1):
    while True:
        s = input(f"  {prompt} [{default}]: ").strip()
        if s == "":
            return int(default)
        try:
            v = int(s)
            if v >= min_val:
                return v
            print(f"    Must be >= {min_val}.")
        except ValueError:
            print("    Please enter an integer.")


def get_bool(prompt, default=False):
    while True:
        s = input(f"  {prompt} [{'Y/n' if default else 'y/N'}]: ").strip().lower()
        if s == "":
            return default
        if s in ("y", "yes"):
            return True
        if s in ("n", "no"):
            return False
        print("    Enter y or n.")


def input_reaction(idx: int, T: float) -> HalfCellReaction:
    print(f"\n  -- Half-Cell Reaction #{idx} (O + n*e- <-> R) --")
    name = input(f"  Name [Rxn{idx}]: ").strip() or f"Rxn{idx}"
    E0 = get_float(f"Formal potential E0 at {T:.2f} K (V)", 0.0)
    n = get_int("Electrons transferred n", 1)
    ks = get_float("Standard rate constant ks (cm/s; large -> reversible)", 1.0)
    alpha = get_float("Transfer coefficient alpha", 0.5)
    C0 = get_float("Bulk concentration C0 (mol/cm^3, e.g. 1e-6 = 1 mM)", 1e-6)
    D_O = get_float("Diffusion coeff D_O (cm^2/s)", 1e-5)
    D_R = get_float("Diffusion coeff D_R (cm^2/s)", 1e-5)

    dS_rxn = 0.0
    Ea = 0.0
    if abs(T - T0) > 0.1:
        print(f"  (T != {T0} K -- optional MECSim thermal correction terms)")
        dS_rxn = get_float("Reaction entropy dS_rxn (J/mol/K); 0 = none", 0.0)
        Ea = get_float("Activation energy Ea (J/mol); 0 = none", 0.0)

    has_ec = get_bool("Add following chemical reaction (EC mechanism)?", False)
    kf_chem = 0.0
    kb_chem = 0.0
    if has_ec:
        kf_chem = get_float("Forward chem rate kf (s^-1)", 10.0)
        kb_chem = get_float("Reverse chem rate kb (s^-1, 0=irreversible)", 0.0)

    return HalfCellReaction(
        name=name, E0=E0, n=n, ks=ks, alpha=alpha,
        C0=C0, D_O=D_O, D_R=D_R,
        has_ec=has_ec, kf_chem=kf_chem, kb_chem=kb_chem,
        dS_rxn=dS_rxn, Ea=Ea,
    )


